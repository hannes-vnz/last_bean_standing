def _bits(src: dict) -> dict[str, tuple[int, list[str]]]:
    return {ch: (g[0], list(g[1:])) for ch, g in src.items()}


BODY = _bits(_BODY_SRC)
TINY = _bits(_TINY_SRC)

_CACHE_MAX = 600


class PixelFont:
    """Drop-in for the used part of ``pygame.font.Font``: ``render``, ``size``, ``get_height``."""

    def __init__(self, glyphs: dict, rows: int, scale: int = 1, bold: bool = False, upper: bool = False) -> None:
        self.glyphs, self.rows, self.scale, self.bold, self.upper = glyphs, rows, scale, bold, upper
        self._masks: dict[str, pygame.Surface] = {}
        self._cache: dict[tuple, pygame.Surface] = {}

    def _text(self, text: str) -> str:
        if not self.upper:
            return text
        text = text.upper()
        return "".join(_TINY_ALIAS.get(ch, ch) for ch in text)

    def _glyph(self, ch: str) -> tuple[int, list[str]]:
        g = self.glyphs.get(ch)
        if g is None:
            g = self.glyphs.get(ch.upper()) or self.glyphs["?"]
        return g

    def _advance(self, ch: str) -> int:
        return len(self._glyph(ch)[1][0]) + 1 + (1 if self.bold else 0)

    def size(self, text: str) -> tuple[int, int]:
        text = self._text(text)
        w = sum(self._advance(ch) for ch in text) - 1 if text else 0
        return max(0, w) * self.scale, self.get_height()

    def get_height(self) -> int:
        return (self.rows + 1) * self.scale

    def _mask(self, ch: str) -> pygame.Surface:
        """White glyph on transparent, already scaled."""
        m = self._masks.get(ch)
        if m is None:
            top, rows = self._glyph(ch)
            w = len(rows[0]) + (1 if self.bold else 0)
            m = pygame.Surface((max(1, w), self.rows), pygame.SRCALPHA)
            for y, row in enumerate(rows):
                for x, bit in enumerate(row):
                    if bit == "#":
                        m.set_at((x, top + y), (255, 255, 255, 255))
                        if self.bold:
                            m.set_at((x + 1, top + y), (255, 255, 255, 255))
            if self.scale > 1:
                m = pygame.transform.scale(m, (m.get_width() * self.scale, m.get_height() * self.scale))
            self._masks[ch] = m
        return m

    def render(self, text: str, antialias: bool = False, color=(255, 255, 255), background=None) -> pygame.Surface:
        key = (text, tuple(color), None if background is None else tuple(background))
        img = self._cache.get(key)
        if img is not None:
            return img
        shown = self._text(text)
        w, h = self.size(text)
        img = pygame.Surface((max(1, w), h), pygame.SRCALPHA)
        x = 0
        for ch in shown:
            img.blit(self._mask(ch), (x, self.scale))
            x += self._advance(ch) * self.scale
        img.fill((*tuple(color)[:3], 255), special_flags=pygame.BLEND_RGBA_MULT)
        if background is not None:
            bg = pygame.Surface(img.get_size(), pygame.SRCALPHA)
            bg.fill(background)
            bg.blit(img, (0, 0))
            img = bg
        if len(self._cache) >= _CACHE_MAX:
            self._cache.clear()
        self._cache[key] = img
        return img


def body_font(scale: int = 1, bold: bool = False) -> PixelFont:
    return PixelFont(BODY, 9, scale, bold)


def tiny_font(scale: int = 1) -> PixelFont:
    return PixelFont(TINY, 5, scale, upper=True)
